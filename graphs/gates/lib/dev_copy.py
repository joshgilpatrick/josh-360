"""The development graph's six comments, word for word (design spec, "Exact copy"; JP-115).

Python 3.9, standard library only. Every comment has the workflow's `result | evidence | next gate` shape. The text
here is what gets posted, so a change to it is a change to the spec.
"""
from __future__ import annotations

from typing import Optional

FOOTER = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"


def pr_opened(url: str, passed: int, total: int, head: str) -> str:
    return "Pull request opened | {} · checks {}/{} on {} | next gate: the PR audit".format(url, passed, total, head)


def returned_question(question: Optional[str], path: str, run_id: str) -> str:
    """The question the designer needs answered; `question` is None when it is withheld as patient data."""
    needs = question if question is not None else "withheld: patient data, see {}".format(path)
    return ("Returned to triage | the designer needs: {} · run {}, spec saved | "
            "next gate: triage answers it, then this run resumes".format(needs, run_id))


def fixes_pushed(n: int, resolution: str, next_gate: str) -> str:
    return "Review fixes pushed ({} finding(s) addressed) | {} | next gate: {}".format(n, resolution, next_gate) + FOOTER


def done_merged(url: str, merge_commit: str, run_id: str, research: bool) -> str:
    kept = ("design and plan merged with it, run {}".format(run_id) if research
            else "spec and evidence saved with run {}".format(run_id))
    return "Done | merged {} as {} · {} | next gate: none".format(url, merge_commit, kept)


def handed_to_watch(url: str, merge_commit: str, run_id: str) -> str:
    return ("Merged, now watched in production | merged {} as {} · spec and evidence saved with run {} | "
            "next gate: the validation watch starts within five minutes; "
            "the ticket is Done when its criteria are met".format(url, merge_commit, run_id))


def cancelled(url: str, run_id: str) -> str:
    return ("Cancelled | {} was closed without merging · spec and evidence saved with run {} | "
            "next gate: Josh reopens the ticket if he wants it built again".format(url, run_id))
